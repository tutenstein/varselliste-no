// Generates src/data/regions.ts and src/data/kommuneGeo.ts.
//   - Kartverket kommuneinfo (CC BY 4.0): fylke and kommune numbers, Norwegian names, other official names
//   - Wikidata (CC0): kommune centre points (P2504 kommune number + P625), validated against Kartverket's
//     bounding box; falls back to Kartverket's `punktIOmrade` (a point guaranteed inside the kommune)
// Run when kommune boundaries change (next known change: 1 Jan 2028):  node scripts/build-regions.mjs
import { writeFile } from "node:fs/promises";

const UA = process.env.INGEST_USER_AGENT || "Varsellisten/0.1 (build; contact pending)";
const KARTVERKET = "https://api.kartverket.no/kommuneinfo/v1/fylkerkommuner";
const WIKIDATA = "https://query.wikidata.org/sparql";
const SPARQL = `SELECT ?item ?num ?rank ?end ?coord ?dissolved WHERE {
  ?item p:P2504 ?st .
  ?st ps:P2504 ?num ; wikibase:rank ?rank .
  OPTIONAL { ?st pq:P582 ?end }
  OPTIONAL { ?item wdt:P625 ?coord }
  OPTIONAL { ?item wdt:P576 ?dissolved }
}`;

async function getJson(url, init = {}) {
  const res = await fetch(url, {
    ...init,
    headers: { "User-Agent": UA, Accept: "application/json", ...init.headers },
    signal: AbortSignal.timeout(120_000),
  });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

/** æ→ae, ø→o, å→a, other diacritics stripped, everything else → "-". */
export function slugify(s) {
  return s
    .toLowerCase()
    .replace(/æ/gu, "ae")
    .replace(/ø/gu, "o")
    .replace(/å/gu, "a")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/gu, "")
    .replace(/[^a-z0-9]+/gu, "-")
    .replace(/^-|-$/gu, "");
}

const round = (n) => Math.round(n * 1e4) / 1e4;

/** One entry per line, sorted by key: readable diffs when kommuner change. */
const lines = (obj) =>
  `{\n${Object.keys(obj)
    .sort()
    .map((k) => `  "${k}": ${JSON.stringify(obj[k])},`)
    .join("\n")}\n}`;

function inBox(box, lng, lat) {
  const ring = box?.coordinates?.[0];
  if (!ring) return false;
  const lngs = ring.map((c) => c[0]);
  const lats = ring.map((c) => c[1]);
  return lng >= Math.min(...lngs) && lng <= Math.max(...lngs) && lat >= Math.min(...lats) && lat <= Math.max(...lats);
}

async function main() {
  const fylker = await getJson(KARTVERKET);
  const wd = await getJson(`${WIKIDATA}?format=json&query=${encodeURIComponent(SPARQL)}`, {
    headers: { Accept: "application/sparql-results+json" },
  });

  // Wikidata: current statements only (no end qualifier, not deprecated, item not dissolved).
  const wdPoints = new Map();
  for (const b of wd.results.bindings) {
    if (b.end || b.dissolved || !b.coord) continue;
    if (b.rank.value.endsWith("DeprecatedRank")) continue;
    const m = /Point\(([-\d.]+) ([-\d.]+)\)/u.exec(b.coord.value);
    if (!m) continue;
    const list = wdPoints.get(b.num.value) ?? [];
    list.push([Number(m[2]), Number(m[1])]); // [lat, lng]
    wdPoints.set(b.num.value, list);
  }

  const FYLKER = {};
  const kommuner = [];
  for (const f of fylker) {
    FYLKER[f.fylkesnummer] = { navn: f.fylkesnavn, slug: slugify(f.fylkesnavn) };
    for (const k of f.kommuner) {
      const navn = k.kommunenavnNorsk || k.kommunenavn;
      const other = (k.gyldigeNavn ?? []).map((g) => g?.navn).filter((n) => n && n !== navn);
      kommuner.push({ nr: k.kommunenummer, navn, fylke: f.fylkesnummer, alias: [...new Set(other)], box: k.avgrensningsboks, punkt: k.punktIOmrade });
    }
  }
  kommuner.sort((a, b) => a.nr.localeCompare(b.nr));

  // Duplicate names (Herøy, Våler) get the fylke name appended to the slug.
  const bySlug = new Map();
  for (const k of kommuner) bySlug.set(slugify(k.navn), (bySlug.get(slugify(k.navn)) ?? 0) + 1);

  const KOMMUNER = {};
  const GEO = {};
  let fromWikidata = 0;
  for (const k of kommuner) {
    const base = slugify(k.navn);
    const slug = bySlug.get(base) > 1 ? `${base}-${FYLKER[k.fylke].slug}` : base;
    KOMMUNER[k.nr] = { navn: k.navn, fylke: k.fylke, slug, ...(k.alias.length ? { alias: k.alias } : {}) };

    const candidate = (wdPoints.get(k.nr) ?? []).find(([lat, lng]) => inBox(k.box, lng, lat));
    if (candidate) {
      GEO[k.nr] = [round(candidate[0]), round(candidate[1])];
      fromWikidata++;
    } else {
      const [lng, lat] = k.punkt.coordinates;
      GEO[k.nr] = [round(lat), round(lng)];
    }
  }

  const slugs = Object.values(KOMMUNER).map((k) => k.slug);
  if (new Set(slugs).size !== slugs.length) throw new Error("kommune slugs are not unique");

  const header = (what) =>
    `// Generated by scripts/build-regions.mjs on ${new Date().toISOString().slice(0, 10)} – do not edit by hand.\n// ${what}\n\n`;

  await writeFile(
    new URL("../src/data/regions.ts", import.meta.url),
    header("Source: Kartverket kommuneinfo (CC BY 4.0). Names are the Norwegian names; `alias` holds other official names.") +
      `export interface FylkeData {\n  navn: string;\n  slug: string;\n}\n\nexport interface KommuneData {\n  navn: string;\n  fylke: string;\n  slug: string;\n  alias?: string[];\n}\n\n` +
      `export const FYLKER: Record<string, FylkeData> = ${lines(FYLKER)};\n\n` +
      `export const KOMMUNER: Record<string, KommuneData> = ${lines(KOMMUNER)};\n`,
  );
  await writeFile(
    new URL("../src/data/kommuneGeo.ts", import.meta.url),
    header("Kommune centre points [lat, lng]: Wikidata P625 (CC0), validated against Kartverket's bounding box; otherwise Kartverket punktIOmrade (CC BY 4.0).") +
      `export const KOMMUNE_GEO: Record<string, [number, number]> = {\n${Object.entries(GEO)
        .map(([nr, [lat, lng]]) => `  "${nr}": [${lat}, ${lng}],`)
        .join("\n")}\n};\n`,
  );
  console.log(
    `regions: ${Object.keys(FYLKER).length} fylker, ${kommuner.length} kommuner; centre points: ${fromWikidata} Wikidata, ${kommuner.length - fromWikidata} Kartverket`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
